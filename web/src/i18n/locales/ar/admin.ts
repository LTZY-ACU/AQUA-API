/**
 * 管理后台页面词条（阿拉伯语 / العربية，RTL）。
 *
 * 意图（Why）：
 *   后台 25 个页面的文案原先硬编码在 JSX 里，切到阿拉伯语时整块界面仍是中文，
 *   混排比"全中文"更糟。抽到词条层之后，语言切换才真正对后台生效。
 *
 * RTL（从右向左）约定：
 *   书写方向由 <html dir="rtl"> 统一处理（i18n/index.ts 的 isRtl('ar')），
 *   本文件不插入任何方向控制字符（U+202B/U+202C 等）——那是 CSS dir 属性的职责，
 *   手动插入反而会与浏览器的双向算法打架。
 *   混排拉丁字符（DNS、API、模型名、数字单位）时按逻辑顺序书写：
 *   数字/拉丁片段放在阿拉伯语词句中作为独立成分，交给 bidi 算法排版。
 *
 * 计数类词条的处理（重要）：
 *   阿拉伯语的数词与名词有性数配合：3–10 要求名词复数（如 5 نماذج / 3 مفاتيح），
 *   11 及以上反而回到单数格（如 15 نموذجًا），而 1、2 又是另一套形式
 *   （نموذج واحد / نموذجان）。i18n 的 t() 只做 {var} 插值，没有复数表单
 *   （Intl.PluralRules 那套），所以"{count} 个模型"直译成
 *   "{count} نموذج" 会在 count=5 时显示成语法错误的单数。
 *   因此凡带计数的词条一律改成「名词标签 + 冒号 + 数字」或把数字放进括号，
 *   让数字脱离与名词的数词配合，例如：
 *     modelCount   → 'النماذج: {count}'   （名词已是泛指复数，: 后的数字是纯数值）
 *     fetchedCount → 'النماذج المجلوبة: {count}'
 *     toast.applied→ 'تمت الإضافة — الجديد: {added}، الإجمالي: {total}'
 *   这样任意数值下都不需要变格，代价是失去"3 个模型"式的口语自然度，
 *   对运维界面而言取值稳定性优先。
 *
 * 流转（Flow）：
 *   i18n/index.ts 合并六种语言 → 页面通过 t('admin.channels.*') 读取。
 *
 * 扩展（Extend）：
 *   键集合必须与 zh-CN/admin.ts 完全一致（index.ts 用 satisfies 在编译期强制）。
 *   本文件是译文，改文案请先改中文基准再同步，避免两种语言说法漂移。
 */
