-- 迁移 0045：模型分组增加「每分钟请求数上限（RPM）」
--
-- 意图（Why）：
--   分组此前只承载"定价"（ratio 倍率、充值门槛、仅后台分发），但它同样是
--   「套餐档位」的天然载体：免费档 / 标准档 / 代理档各自该有怎样的调用速率。
--
--   本列把"这个分组每分钟最多打多少次"变成数据，补上额度墙之外的第二道闸门：
--   账号/令牌额度管的是【总量】，而一个失控令牌的短时高频（每秒几十次）在
--   几分钟内就能吃掉整月毛利，总量闸门对此完全无感（它看的是累计值不是速率）。
--   RPM 上限正是在速率维度上兜底。
--
-- 为什么放在分组而不是令牌上：
--   同一档位的令牌应当共用一份速率承诺；挂在分组上，管理员调整一次即对该档
--   全部令牌生效，不必逐令牌维护——与倍率、门槛的归属维度保持一致。
--
-- 取值语义：
--   0    = 不限（默认，也是全部历史数据的取值）：与迁移前的行为逐字一致，
--          请求链路上"零成本放行"（不查分组、不入计数表）。
--   > 0  = 该分组每分钟允许的请求数上限；超出返回 429（error code
--          quota.group_rpm_exceeded）。
--
-- 计数口径与代价（务必知悉）：
--   计数为【进程内固定 1 分钟窗口】（见 internal/server/middleware/group_rate_limit.go）。
--   单实例部署下即精确的每分钟上限；多实例部署时各实例各算一份，
--   实际全局速率约为"上限 × 实例数"。之所以先做进程内：不引入 Redis/外部依赖，
--   改动半径最小，重启即清零；日后确需跨实例共享时，替换计数底层即可，调用点不变。
--
-- 兼容性：
--   只加列、不改既有列，默认 0（不限）保证升级后既有分组行为逐字不变。
--
-- 流转（Flow）：
--   model_groups.rpm_limit
--     → model.ModelGroup.RpmLimit
--     → store/group_repo.go 的读列 / 写列
--     → middleware.GroupRPMLimiter 取该分组上限并计数 → 超限 429
--
-- 扩展（Extend）：
--   若将来需要"按令牌单独覆盖分组上限"或"秒级限流"，在此之上另加列/另建限流器，
--   不要修改本文件（历史迁移禁止改动）。

ALTER TABLE model_groups ADD COLUMN rpm_limit INTEGER NOT NULL DEFAULT 0;
